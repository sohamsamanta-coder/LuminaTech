class Command(BaseCommand):
    help = "Create or update the demo electronics products."

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0

        for product_data in PRODUCTS:
            name = product_data["name"]

            product, created = Product.objects.update_or_create(
                name=name,
                defaults=product_data,
            )

            if created:
                created_count += 1
            else:
                updated_count += 1

            specifications = PRODUCT_SPECS.get(name, [])

            for order, (label, value) in enumerate(specifications, start=1):
                ProductSpecification.objects.get_or_create(
                    product=product,
                    label=label,
                    defaults={
                        "value": value,
                        "order": order,
                    },
                )

        self.stdout.write(
            self.style.SUCCESS(
                f"Seed complete: {created_count} created, {updated_count} updated."
            )
        )
